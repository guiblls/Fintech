WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
CREATE SEQUENCE FC7_USUARIO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FC7_CONTA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FC7_INVESTIMENTO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FC7_USUARIO (
 id NUMBER(19) PRIMARY KEY, nome VARCHAR2(120 CHAR) NOT NULL,
 email VARCHAR2(180 CHAR) NOT NULL UNIQUE, senha_hash VARCHAR2(255 CHAR) NOT NULL,
 cpf VARCHAR2(11 CHAR) NOT NULL UNIQUE, telefone VARCHAR2(20 CHAR), data_cadastro DATE NOT NULL
);
CREATE TABLE FC7_CONTA (
 id NUMBER(19) PRIMARY KEY, saldo NUMBER(15,2) DEFAULT 0 NOT NULL CHECK(saldo>=0),
 tipo_conta VARCHAR2(20 CHAR) NOT NULL CHECK(tipo_conta IN ('CORRENTE','POUPANCA','DINHEIRO')),
 status_conta VARCHAR2(10 CHAR) NOT NULL CHECK(status_conta IN ('ATIVA','INATIVA')),
 data_abertura DATE NOT NULL, id_usuario NUMBER(19) NOT NULL REFERENCES FC7_USUARIO(id)
);
CREATE TABLE FC7_INVESTIMENTO (
 id NUMBER(19) PRIMARY KEY, id_conta NUMBER(19) NOT NULL REFERENCES FC7_CONTA(id),
 nome_investimento VARCHAR2(120 CHAR) NOT NULL, tipo_investimento VARCHAR2(40 CHAR) NOT NULL,
 valor_aplicado NUMBER(15,2) NOT NULL CHECK(valor_aplicado>0),
 rentabilidade NUMBER(7,2) NOT NULL CHECK(rentabilidade>=-100),
 data_aplicacao DATE NOT NULL, prazo NUMBER(10) NOT NULL CHECK(prazo BETWEEN 0 AND 1200),
 status_investimento VARCHAR2(12 CHAR) NOT NULL CHECK(status_investimento IN ('ATIVO','RESGATADO'))
);
CREATE INDEX FC7_CONTA_USUARIO_IX ON FC7_CONTA(id_usuario);
CREATE INDEX FC7_INV_CONTA_IX ON FC7_INVESTIMENTO(id_conta);
